/** Words in the table, with the same casing rules the rules use for replacements. */
export function synonymsFor(word: string): string[] {
  const lower = word.toLowerCase();
  const list = GROUPS[lower];
  if (!list) return [];
  const caps = word.length > 1 && word === word.toUpperCase();
  const initial = !caps && word[0] !== lower[0];
  return list.map((s) => (caps ? s.toUpperCase() : initial ? s[0].toUpperCase() + s.slice(1) : s));
}
